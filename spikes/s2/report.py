"""Combine results/amd64.json and results/arm64.json into results/matrix.md.

    uv run python spikes/s2/report.py
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOLS = ["testssl.sh", "s_client", "ssh-audit", "theia", "zeek", "opengrep"]
CAPS = ["C1", "C2", "C3", "C4", "C5", "C6", "C7", "C8", "C9"]
APPLICABLE = {("C1", "testssl.sh"), ("C1", "s_client"), ("C1", "zeek"), ("C2", "ssh-audit"),
              ("C3", "testssl.sh"), ("C3", "s_client"), ("C3", "theia"), ("C4", "testssl.sh"),
              ("C4", "s_client"), ("C5", "testssl.sh"), ("C5", "s_client"), ("C6", "testssl.sh"),
              ("C6", "s_client"), ("C7", "testssl.sh"), ("C7", "s_client"), ("C8", "zeek"),
              ("C9", "opengrep")}
PREDICTED = {("C3", "testssl.sh"): "wrong or fails", ("C3", "theia"): "wrong or blind"}


def load(arch):
    p = HERE / "results" / f"{arch}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def main():
    res = {a: load(a) for a in ("amd64", "arm64")}
    lines = ["# S2 results — the matrix", "",
             "Each cell: the outcome on x86_64 / on arm64 under qemu-user. Generated by `report.py` from",
             "`amd64.json` and `arm64.json`; every outcome's raw output is under `results/<arch>/` with its",
             "SHA-256 in those files.", "",
             "| | " + " | ".join(TOOLS) + " |", "|---|" + "---|" * len(TOOLS)]
    unfilled, differ, surprises = [], [], []
    for cap in CAPS:
        row = [cap]
        for tool in TOOLS:
            if (cap, tool) not in APPLICABLE:
                row.append("—")
                continue
            o = [res[a].get(f"{cap}|{tool}", {}).get("outcome", "—") for a in ("amd64", "arm64")]
            for a, v in zip(("amd64", "arm64"), o, strict=True):
                detail = res[a].get(f"{cap}|{tool}", {}).get("detail", "")
                if v in ("—", "not run"):
                    unfilled.append(f"{cap} {tool} on {a}")
                elif v == "fails" and "pcap_error" in detail:
                    # The emulator's failure, not the tool's: qemu-user cannot open a packet socket.
                    unfilled.append(f"{cap} {tool} on {a} (packet capture does not run under qemu-user)")
            if o[0] != o[1] and "—" not in o:
                differ.append(f"{cap} {tool}: {o[0]} on x86_64, {o[1]} on arm64")
            pred = PREDICTED.get((cap, tool))
            if pred and o[0] not in pred:
                surprises.append(f"{cap} {tool}: predicted {pred}, observed {o[0]}")
            row.append(o[0] if o[0] == o[1] else f"{o[0]} / {o[1]}")
        lines.append("| " + " | ".join(row) + " |")
    lines += ["", "## Details, x86_64", ""]
    for k, v in sorted(res["amd64"].items()):
        lines.append(f"- **{k.replace('|', ', ')}**: {v['outcome']} — {v['detail']} ({v['seconds']} s)")
    lines += ["", "## Details, arm64 under qemu-user (times are emulated, not GB10 numbers)", ""]
    for k, v in sorted(res["arm64"].items()):
        lines.append(f"- **{k.replace('|', ', ')}**: {v['outcome']} — {v['detail']} ({v['seconds']} s)")
    lines += ["", "## Against the criterion", "",
              f"- Unfilled applicable cells: {', '.join(unfilled) or 'none'}",
              f"- Cells that differ between architectures: {', '.join(differ) or 'none'}",
              f"- Outcomes against prediction: {', '.join(surprises) or 'as predicted'}",
              f"- S2 {'passes' if not unfilled else 'does not pass yet'}."]
    (HERE / "results" / "matrix.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:16]))
    print("\n".join(lines[-5:]))


if __name__ == "__main__":
    main()
