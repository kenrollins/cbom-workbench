"""The licence table (FR-05): every Python dependency the harness ships, from the installed packages'
own metadata; every scanner image the runner pins; every vendored asset.

    uv run python tools/licences.py            # writes docs/LICENCES.md

Python rows are read, not typed: the locked runtime dependencies (`uv export --no-dev`), each one's
licence as its installed metadata declares it (License-Expression, else License, else the classifiers).
The scanner and asset rows are the licences their projects declare, typed here and marked *verify*
until someone reads each project's licence file on the date shown.
"""

from __future__ import annotations

import re
import subprocess
import sys
from importlib import metadata
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "LICENCES.md"

# Typed, from each project's declared licence; *verify* until each licence file is read and dated.
SCANNERS = {"testssl.sh": "GPL-2.0-only", "ssh-audit": "MIT", "cbomkit-theia": "Apache-2.0"}
OTHER = [
    ("Zeek (capture service)", "BSD-3-Clause", "capture/"),
    ("OpenSSL (the harness image's command line and libraries)", "Apache-2.0", "Dockerfile base image"),
    ("OpenSSH client", "BSD-style (OpenSSH licence)", "Dockerfile, Debian package"),
    ("d3 v7", "ISC", "src/pqch/ui/static/vendor/d3.v7.min.js"),
    ("Inter, JetBrains Mono, EB Garamond, Caveat, Jost (fonts)", "OFL-1.1", "src/pqch/ui/static/fonts/"),
]


def _licence(dist: metadata.Distribution) -> str:
    m = dist.metadata
    if m.get("License-Expression"):
        return m["License-Expression"]
    lic = (m.get("License") or "").strip()
    if lic and len(lic) < 80 and "\n" not in lic:
        return lic
    cls = [c.split(" :: ")[-1] for c in m.get_all("Classifier") or [] if c.startswith("License ::")]
    return "; ".join(cls) or (lic.splitlines()[0][:60] + "…" if lic else "not declared")


def python_rows() -> list[tuple[str, str, str]]:
    req = subprocess.run(["uv", "export", "--frozen", "--no-dev", "--no-emit-project", "--no-hashes",
                          "--format", "requirements-txt"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    rows = []
    for line in req.splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)", line)
        if not m:
            continue
        name, version = m.groups()
        try:
            lic = _licence(metadata.distribution(name))
        except metadata.PackageNotFoundError:
            lic = "not installed here"
        rows.append((name, version, lic))
    return sorted(rows, key=lambda r: r[0].lower())


def render() -> str:
    profiles = yaml.safe_load((ROOT / "src" / "pqch" / "runner" / "profiles.yaml").read_text())
    images = sorted({(p["tool"], str(p.get("version")), p["image"]) for p in profiles.values() if p.get("image") != "self"})
    out = ["# Licences", "",
           "<!-- generated by tools/licences.py; do not edit by hand -->", "",
           "The workbench itself is Apache-2.0 (`LICENSE`). What it ships with or runs:", "",
           "## Scanner images the runner pins", "",
           "| Tool | Version | Image | Licence |", "|---|---|---|---|"]
    out += [f"| {t} | {v} | `{i.split('@')[0]}@{i.split('@')[1][:19]}…` | {SCANNERS.get(t, 'not recorded')} *verify* |"
            for t, v, i in images]
    out += ["", "## Other components and vendored assets", "", "| Component | Licence | Where |", "|---|---|---|"]
    out += [f"| {n} | {lic} *verify* | `{w}` |" for n, lic, w in OTHER]
    out += ["| axe-core 4.11.2 (test asset, never served) | MPL-2.0 (its `LICENSE`, read) | `tests/vendor/axe-core/` |",
            "", "## Python dependencies (locked, runtime)", "",
            "Read from each installed package's metadata when this page was generated.", "",
            "| Package | Version | Licence as declared |", "|---|---|---|"]
    out += [f"| {n} | {v} | {lic} |" for n, v, lic in python_rows()]
    out += ["", "Debian packages in the harness image carry their own copyright files; the image's SBOM "
            "(`tools/sbom.py`) lists each with the licences Syft read from them.", ""]
    return "\n".join(out)


def main() -> int:
    OUT.write_text(render())
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
