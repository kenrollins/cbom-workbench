"""Render the role cards (FR-07) from eval/role-cards.yaml, spike S3's scored report and an inference
config's bindings, into site_src/role-cards.md.

    uv run python tools/role_cards.py [--config kit/inference.yaml] [--check]

`--check` exits 1 when the page on disk is not what the sources render (the test runs it).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CARDS = ROOT / "eval" / "role-cards.yaml"
REPORT = ROOT / "spikes" / "s3" / "results" / "scored" / "report.json"
OUT = ROOT / "site_src" / "role-cards.md"


def measured(m: dict, report: dict) -> dict:
    if "report" in m:
        r = report[m["report"]][m["arm"]]
        return {**m, "correct": r["correct"], "of": r["items"], "harmful": r["harmful"],
                "source": f"spike S3 scored report, {m['report'].upper()}, arm `{m['arm']}`"}
    return m


def clears(m: dict, floor: dict | None) -> str:
    if not floor:
        return "no floor written"
    need = -(-floor["correct"] * m["of"] // floor["of"])          # a smaller item set scales the floor, rounded up
    verdict = "reaches the floor" if m["correct"] >= need and m["harmful"] <= floor["harmful"] else "below the floor"
    if m["of"] != floor["of"]:
        # The floor was written for another item count; the comparison is against it scaled, and says so.
        verdict += f" scaled to {m['of']} items (ceil({floor['correct']}·{m['of']}/{floor['of']}) = {need})"
    return verdict


def render(config_path: Path) -> str:
    cards = yaml.safe_load(CARDS.read_text())["roles"]
    report = json.loads(REPORT.read_text())
    cfg = yaml.safe_load(config_path.read_text())
    bound = cfg.get("roles") or {}
    rel = config_path.resolve().relative_to(ROOT) if config_path.resolve().is_relative_to(ROOT) else config_path.name
    out = ["---", "title: Model role cards", "---", "", "# Model role cards", "",
           "<!-- generated by tools/role_cards.py from eval/role-cards.yaml, spike S3's scored report and "
           f"{rel}; do not edit by hand -->", "",
           "Every place a language model takes part in the workbench, one card each: what the role decides, what "
           "data it sees, the floor written before it was measured, what was measured on which model and hardware, "
           "what checks its output, and what happens when no model answers. Bindings are those of "
           f"`{rel}`; a deployment's own config may bind differently, and only by measurement.", "",
           "## How models are used here, in one paragraph", "",
           "Models inform; rules and people decide. No model decides whether a change worked: that is a re-scan, "
           "a certificate parse or a pair of probes. No model output enters the inventory unlabelled: the one "
           "model-set fact in the CBOM (a code line's in-use) carries the model, engine and hardware that set it. "
           "Every call is on the ledger with its model, tier, hardware and, where the endpoint says, the engine that "
           "served it. Inference runs on the deployment's own hardware through one seam, which can refuse a model "
           "whose declared origin is not on an allowlist. A role moves to a model only when a model reaches a floor "
           "written before the run.", ""]
    for role, c in cards.items():
        b = bound.get(role)
        out += [f"## `{role}`" + (f" (spike S3 {c['s3']})" if c.get("s3") else ""), "",
                "| | |", "|---|---|",
                f"| Decides | {c['decides']} |", f"| Sees | {c['sees']} |", f"| Output | {c['output']} |",
                f"| What gates it | {c['gate']} |",
                f"| Floor | {c['floor']['correct']} of {c['floor']['of']}, {c['floor']['harmful']} harmful allowed"
                + (f" ({c['floor']['note']})" if c['floor'].get('note') else "") + " |" if c.get("floor") else "| Floor | none written; unmeasured |",
                f"| Bound in this config | {'tier `' + b['tier'] + '`' + (', reasoning on' if b.get('reasoning') else ', reasoning off') if b else 'not bound: no model is called'} |",
                f"| When no model answers | {c['unavailable']} |", ""]
        ms = [measured(m, report) for m in c.get("measured") or []]
        if ms:
            out += ["| Measured | Hardware | Date | Correct | Harmful | Against the floor | Source |", "|---|---|---|---|---|---|---|"]
            out += [f"| {m['label']} | {m['hardware']} | {m['date']} | {m['correct']} of {m['of']} | {m['harmful']} | "
                    f"{clears(m, c.get('floor'))} | {m['source']} |" for m in ms]
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--config", default=str(ROOT / "kit" / "inference.yaml"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render(Path(a.config))
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        print("role cards are current" if ok else f"{OUT} differs from what its sources render", file=sys.stderr)
        return 0 if ok else 1
    OUT.write_text(text)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
