#!/usr/bin/env python
"""Copy the journal into the site source and write its index pages.

`docs/journal/notes/` and `docs/journal/lessons/` stay the single copy of every
entry; the site is built from a verbatim copy, so the repository and the
published pages cannot drift. The index pages are generated from each entry's
frontmatter, so an entry is published the moment it exists -- there is no
hand-maintained list to forget.

Run:  python tools/build_site.py   (then `mkdocs build --strict`)
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "site_src"
JOURNAL = ROOT / "docs" / "journal"

SECTIONS = {
    "notes": ("Technical notes", "One question per note, answered with measured or cited evidence."),
    "lessons": ("Lessons", "Standing guidance: the rule, why it holds, when it applies."),
}

FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def _field(front: str, key: str) -> str:
    m = re.search(rf"^{key}:\s*(.+)$", front, re.M)
    if not m:
        return ""
    # A quoted YAML scalar: the outer quotes go, and an escaped quote inside is a quote.
    return m.group(1).strip().strip('"').replace('\\"', '"')


def copy_section(name: str) -> list[tuple[str, str, str, str]]:
    src, dst = JOURNAL / name, SRC / name
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    rows = []
    for path in sorted(src.glob("[0-9][0-9]-*.md")):
        text = path.read_text(encoding="utf-8")
        m = FRONT.match(text)
        front = m.group(1) if m else ""
        title = _field(front, "title") or path.stem
        one_line = _field(front, "one_line")
        date = _field(front, "date")
        shutil.copy2(path, dst / path.name)
        rows.append((path.name, title, one_line, date))
    return rows


def write_index(name: str, rows: list[tuple[str, str, str, str]]) -> None:
    heading, blurb = SECTIONS[name]
    lines = [f"---\ntitle: {heading}\n---\n", f"# {heading}\n", f"{blurb}\n"]
    if not rows:
        lines.append("\nNo entries published yet.\n")
    else:
        # Numbered as the sidebar is ("04 — …"), the number written in ballpoint (.fn-entries, fieldnotes.css).
        lines.append('\n<ol class="fn-entries" markdown="1">')
        for fname, title, one_line, _ in rows:
            entry = f"[{title}]({fname})" + (f" — {one_line}" if one_line else "")
            lines.append(f'<li markdown="span"><span class="fn-num">{fname[:2]}</span> {entry}</li>')
        lines.append("</ol>")
    (SRC / name / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def journal_span(first: str, last: str) -> str:
    """Two ISO dates as the handwritten line: short enough to sit under the label without widening
    the box. "Oct 4 → Nov 4, 2026" within a year; "Oct 4, 2026 → Jan 2, 2027" across one; one date alone."""
    from datetime import date

    def md(d: date) -> str:
        return f"{d.strftime('%b')} {d.day}"

    a, b = date.fromisoformat(first), date.fromisoformat(last)
    if a == b:
        return f"{md(a)}, {a.year}"
    if a.year == b.year:
        return f"{md(a)} \u2192 {md(b)}, {a.year}"
    return f"{md(a)}, {a.year} \u2192 {md(b)}, {b.year}"


def write_span(all_rows: dict) -> None:
    """The handwritten line under FIELD NOTES on the cover: the first entry's date and the latest's.
    Written into mkdocs.yml for the site's header and into site_src/journal-span.txt, which the
    build copies into site/ for the app's header to read."""
    dates = sorted(d for rows in all_rows.values() for _, _, _, d in rows if d)
    span = journal_span(dates[0], dates[-1]) if dates else ""
    yml = ROOT / "mkdocs.yml"
    yml.write_text(re.sub(r'^  journal_span: .*# >>> generated$', f'  journal_span: "{span}"   # >>> generated',
                          yml.read_text(encoding="utf-8"), flags=re.M), encoding="utf-8")
    (SRC / "journal-span.txt").write_text(span + "\n", encoding="utf-8")


def write_nav(all_rows: dict[str, list[tuple[str, str, str, str]]], adrs: list[tuple[str, str, str, str, str]]) -> None:
    """The Technical Notes, Lessons and Decisions entries of mkdocs.yml's nav, generated: a hand-kept
    list falls behind the moment an entry is added without a row."""
    yml = ROOT / "mkdocs.yml"
    text = yml.read_text(encoding="utf-8")
    start, end = "  # >>> generated by tools/build_site.py", "  # <<< end generated"
    a, b = text.index(start), text.index(end)
    # The decisions first: what the notes and lessons rest on is read before them.
    lines = ["  - Decisions:", "      - Overview: adr/index.md"]
    for fname, number, title, _, _ in adrs:
        lines.append(f"      - {json.dumps(f'{number[-2:]} — {title}')}: adr/{fname}")
    for name, rows in all_rows.items():
        heading = SECTIONS[name][0]
        lines.append(f"  - {heading}:")
        lines.append(f"      - Overview: {name}/index.md")
        for fname, title, _, _ in rows:
            label = json.dumps(f"{fname[:2]} — {title.replace(chr(92) + chr(34), chr(34))}")   # a YAML key, quoted
            lines.append(f"      - {label}: {name}/{fname}")
    head = text[:a].rstrip("\n") + "\n" + start + " from docs/adr and docs/journal — do not edit by hand\n"
    yml.write_text(head + "\n".join(lines) + "\n" + text[b:], encoding="utf-8")


ADR_LINE = re.compile(r"\A# ADR-(\d{4}): (.+)$", re.M)


def copy_adrs() -> list[tuple[str, str, str, str, str]]:
    """The decision records, copied verbatim from docs/adr/ with an index: the field notes say what was
    measured and learned; the decisions say what everything else rests on, and a reader should find
    both in one place. A record's number, title, status and date come from its own first lines."""
    src, dst = ROOT / "docs" / "adr", SRC / "adr"
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    rows = []
    for path in sorted(src.glob("[0-9][0-9][0-9][0-9]-*.md")):
        text = path.read_text(encoding="utf-8")
        m = ADR_LINE.match(text)
        number, title = (m.group(1), m.group(2)) if m else (path.stem[:4], path.stem)
        # The status's first sentence: a superseded record explains itself over several lines.
        status = re.search(r"^- \*\*Status:\*\* ([^.\n]+)", text, re.M)
        date = re.search(r"^- \*\*Date:\*\* (\S+)", text, re.M)
        shutil.copy2(path, dst / path.name)
        rows.append((path.name, number, title, status.group(1).strip() if status else "", date.group(1) if date else ""))
    lines = ["---\ntitle: Decisions\n---\n", "# Decisions\n",
             "An ADR is an **architecture decision record**: one page per decision that everything else rests "
             "on, with the context it was made in, the decision itself, what it costs, and the alternatives "
             "rejected. Each is the file in the repository's `docs/adr/`, unchanged, numbered in the order "
             "the decisions were made. A superseded record stays, marked, so the reasoning that was "
             "replaced can still be read.\n",
             '\n<ol class="fn-entries" markdown="1">']
    for fname, number, title, status, date in rows:
        tail = " — ".join(x for x in (date, status) if x)
        # Two digits in the margin, as the notes and lessons are numbered; the record's own heading carries ADR-00NN.
        lines.append(f'<li markdown="span"><span class="fn-num">{number[-2:]}</span> [{title}]({fname})'
                     + (f" <small>({tail})</small>" if tail else "") + "</li>")
    lines.append("</ol>")
    (dst / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return rows


def copy_header() -> None:
    """The demo's header stylesheet and vendored fonts, so the site's header is the demo's own
    (site_overrides/partials/header.html emits the same markup as the app's _header.html)."""
    static = ROOT / "src" / "pqch" / "ui" / "static"
    dst = SRC / "stylesheets" / "fonts"
    dst.mkdir(parents=True, exist_ok=True)
    for f in (static / "fonts").glob("*.woff2"):
        shutil.copy2(f, dst / f.name)
    shutil.copy2(static / "header.css", SRC / "stylesheets" / "header.css")


def main() -> None:
    copy_header()
    all_rows = {}
    for name in SECTIONS:
        rows = copy_section(name)
        write_index(name, rows)
        all_rows[name] = rows
        print(f"{name}: {len(rows)} entries")
    adrs = copy_adrs()
    print(f"decisions: {len(adrs)} records")
    write_nav(all_rows, adrs)
    write_span(all_rows)
    # The sources list is kept once, in docs/; the site shows the same file.
    shutil.copy2(ROOT / "docs" / "SOURCES.md", SRC / "sources.md")
    # The journal's sketches travel with it (tools/draw.py writes them); `../img/sketches/` from an
    # entry resolves the same in the repository and on the site.
    sketches = SRC / "img" / "sketches"
    if sketches.exists():
        shutil.rmtree(sketches)
    if (JOURNAL / "img" / "sketches").exists():
        # The drawings only: the survey and progress files a drawing session keeps beside them
        # (PLAN.md, PROGRESS.md) are working notes, not entries, and stay off the site.
        shutil.copytree(JOURNAL / "img" / "sketches", sketches,
                        ignore=lambda d, names: [n for n in names if not n.endswith(".svg") and not (Path(d) / n).is_dir()])
    # The running workbench's screens, captured by tools/screenshots.py for "page by page" (ADR-0006).
    pages = SRC / "img" / "pages"
    if pages.exists():
        shutil.rmtree(pages)
    if (JOURNAL / "img" / "pages").exists():
        shutil.copytree(JOURNAL / "img" / "pages", pages, ignore=lambda d, names: [n for n in names if not n.endswith(".png")])


if __name__ == "__main__":
    main()
