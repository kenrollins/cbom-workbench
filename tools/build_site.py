#!/usr/bin/env python
"""Copy the journal into the site source and write its index pages.

`docs/journal/notes/` and `docs/journal/lessons/` stay the single copy of every
entry; the site is built from a verbatim copy, so the repository and the
published pages cannot drift. The index pages are generated from each entry's
frontmatter, so an entry is published the moment it exists -- there is no
hand-maintained list to forget.

Run:  python tools/build_site.py   (then `mkdocs build --strict`)
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "site_src"
JOURNAL = ROOT / "docs" / "journal"

SECTIONS = {
    "notes": ("Technical notes", "One question per note, answered with measured or cited evidence."),
    "lessons": ("Lessons", "Standing guidance: the rule, why it holds, when it applies."),
}

FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def _field(front: str, key: str) -> str:
    m = re.search(rf"^{key}:\s*(.+)$", front, re.M)
    if not m:
        return ""
    return m.group(1).strip().strip('"')


def copy_section(name: str) -> list[tuple[str, str, str]]:
    src, dst = JOURNAL / name, SRC / name
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    rows = []
    for path in sorted(src.glob("[0-9][0-9]-*.md")):
        text = path.read_text(encoding="utf-8")
        m = FRONT.match(text)
        front = m.group(1) if m else ""
        title = _field(front, "title") or path.stem
        one_line = _field(front, "one_line")
        shutil.copy2(path, dst / path.name)
        rows.append((path.name, title, one_line))
    return rows


def write_index(name: str, rows: list[tuple[str, str, str]]) -> None:
    heading, blurb = SECTIONS[name]
    lines = [f"---\ntitle: {heading}\n---\n", f"# {heading}\n", f"{blurb}\n"]
    if not rows:
        lines.append("\nNo entries published yet.\n")
    for fname, title, one_line in rows:
        lines.append(f"\n- [{title}]({fname})" + (f" — {one_line}" if one_line else ""))
    (SRC / name / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_nav(all_rows: dict[str, list[tuple[str, str, str]]]) -> None:
    """The Technical Notes and Lessons entries of mkdocs.yml's nav, generated: a hand-kept
    list falls behind the moment an entry is added without a row."""
    yml = ROOT / "mkdocs.yml"
    text = yml.read_text(encoding="utf-8")
    start, end = "  # >>> generated by tools/build_site.py", "  # <<< end generated"
    a, b = text.index(start), text.index(end)
    lines = []
    for name, rows in all_rows.items():
        heading = SECTIONS[name][0]
        lines.append(f"  - {heading}:")
        lines.append(f"      - Overview: {name}/index.md")
        for fname, title, _ in rows:
            label = json.dumps(f"{fname[:2]} — {title.replace(chr(92) + chr(34), chr(34))}")   # a YAML key, quoted
            lines.append(f"      - {label}: {name}/{fname}")
    head = text[:a].rstrip("\n") + "\n" + start + " from docs/journal — do not edit by hand\n"
    yml.write_text(head + "\n".join(lines) + "\n" + text[b:], encoding="utf-8")


def copy_fonts() -> None:
    """The demo's vendored fonts, so the shared header sets in the same face on the site."""
    dst = SRC / "stylesheets" / "fonts"
    dst.mkdir(parents=True, exist_ok=True)
    for f in (ROOT / "src" / "pqch" / "ui" / "static" / "fonts").glob("*.woff2"):
        shutil.copy2(f, dst / f.name)


def main() -> None:
    copy_fonts()
    all_rows = {}
    for name in SECTIONS:
        rows = copy_section(name)
        write_index(name, rows)
        all_rows[name] = rows
        print(f"{name}: {len(rows)} entries")
    write_nav(all_rows)
    # The sources list is kept once, in docs/; the site shows the same file.
    shutil.copy2(ROOT / "docs" / "SOURCES.md", SRC / "sources.md")


if __name__ == "__main__":
    main()
